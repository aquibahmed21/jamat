/** Replaces {name} placeholders. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export type Lang = "en" | "roman";
export const LANGS: readonly Lang[] = ["en", "roman"];
export type RouteKey = keyof typeof en.nav;

const dicts: Record<Lang, Dict> = { en, roman };
const STORAGE_KEY = "jamat.lang";
const listeners = new Set<() => void>();
let current: Lang = "en";

function isLang(v: unknown): v is Lang {
  return typeof v === "string" && (LANGS as readonly string[]).includes(v);
}

/** Current text dictionary. */
export function gt(): Dict {
  return dicts[current];
}

export function getLanguage(): Lang {
  return current;
}

/** Restores the saved language preference (UI preference only; storage may be unavailable). */
export function loadLanguage(): void {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (isLang(saved)) current = saved;
  } catch { /* storage unavailable: keep default */ }
}

export function setLanguage(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  listeners.forEach((fn) => fn());
}

export function onLanguageChange(fn: () => void): void {
  listeners.add(fn);
}

